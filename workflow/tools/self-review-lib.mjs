#!/usr/bin/env node
// Shared helpers for deterministic self-reviews and Markdown rendering.
//
// The goal is to keep the machine-readable JSON as the single source of truth
// and render the human-readable review from it. AI self-reviews fill judgment
// fields only; they never recompute hashes or automated checks.
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

export const toolDir = path.dirname(fileURLToPath(import.meta.url))

export function sha256File(file) {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex')
}

export function relativePath(file, root = process.cwd()) {
  return path.relative(root, path.resolve(file)).split(path.sep).join('/')
}

export function artifact(file, root = process.cwd()) {
  return { path: relativePath(file, root), sha256: sha256File(file) }
}

export function collectArtifacts(files, root = process.cwd()) {
  const seen = new Set()
  const out = []
  for (const file of files) {
    if (!file || !fs.existsSync(file)) continue
    const rel = relativePath(file, root)
    if (seen.has(rel)) continue
    seen.add(rel)
    out.push(artifact(file, root))
  }
  return out
}

function escapeCell(value) {
  return String(value ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>')
}

function firstLine(text) {
  return String(text || '')
    .split(/\r?\n/)
    .map((line) => line.trim())
    .find(Boolean) || ''
}

function summarizeOutput(output) {
  const text = String(output || '').trim()
  if (!text) return 'ok'
  if (text.startsWith('{') || text.startsWith('[')) {
    try {
      const data = JSON.parse(text)
      if (data && data.ok === false) return 'failed'
      if (data && Array.isArray(data.slides)) return `${data.slides.length} slide(s)`
      if (data && Array.isArray(data.questions)) return `${data.questions.length} question(s)`
      if (data && data.verdict) return `verdict ${data.verdict}`
      return 'ok'
    } catch {
      // fall through to the first line
    }
  }
  return firstLine(text).replace(/^OK\s+/, '')
}

export function runTool(tool, args, { root = process.cwd(), timeout = 120000 } = {}) {
  const result = spawnSync(process.execPath, [path.join(toolDir, tool), ...args], {
    cwd: root,
    encoding: 'utf8',
    timeout,
  })
  const pass = result.status === 0
  const output = (result.stdout || '').trim()
  const error = (result.stderr || '').trim()
  const summary = pass ? summarizeOutput(output) : firstLine(error) || firstLine(output) || `exit ${result.status}`
  return {
    name: tool,
    status: pass ? 'pass' : 'fail',
    notes: summary,
    stdout: output,
    stderr: error,
  }
}

function renderDensity(density) {
  if (!Array.isArray(density) || density.length === 0) return []
  const lines = ['## 逐屏语义单元', '', '| 屏 | 语义单元 | 工具信号 | 结论 | 说明 |', '|---|---|---|---|---|']
  for (const entry of density) {
    const units = (entry.semanticUnits || [])
      .map((unit) => `${unit.label}：${unit.evidence}`)
      .join('<br>')
    const signals = Object.entries(entry.signals || {})
      .map(([key, value]) => `${key}=${value}`)
      .join(' ')
    lines.push(
      `| ${escapeCell(entry.slideId)} | ${escapeCell(units)} | ${escapeCell(signals)} | ${escapeCell(entry.verdict)} | ${escapeCell(entry.notes)} |`,
    )
  }
  lines.push('')
  return lines
}

function renderConcepts(concepts) {
  if (!Array.isArray(concepts) || concepts.length === 0) return []
  const lines = ['## 核心概念', '', '| 概念 | 结论 | 证据 | 屏 |', '|---|---|---|---|']
  for (const entry of concepts) {
    lines.push(
      `| ${escapeCell(entry.conceptId)} | ${escapeCell(entry.verdict)} | ${escapeCell(entry.evidence)} | ${escapeCell((entry.slideIds || []).join(', '))} |`,
    )
  }
  lines.push('')
  return lines
}

export function renderSelfReviewMarkdown(review, options = {}) {
  const lines = []
  lines.push(`# AI 自审：${review.stage}`, '')
  lines.push(`- 结论：**${review.verdict}**`)
  lines.push(`- 审核时间：${review.reviewedAt}`)
  if (review.autoGenerated) lines.push('- 生成方式：确定性汇总（无 AI 复核）')
  lines.push('')

  if (Array.isArray(review.artifactPaths) && review.artifactPaths.length) {
    lines.push('## 被审产物', '')
    lines.push('| 产物 | SHA-256 |', '|---|---|')
    for (const item of review.reviewedArtifacts || []) {
      lines.push(`| ${escapeCell(item.path)} | \`${item.sha256.slice(0, 16)}…\` |`)
    }
    lines.push('')
  }

  if (Array.isArray(review.automatedChecks) && review.automatedChecks.length) {
    lines.push('## 自动检查', '', '| 检查 | 结果 | 摘要 |', '|---|---|---|')
    for (const check of review.automatedChecks) {
      lines.push(
        `| ${escapeCell(check.name)} | ${escapeCell(check.status)} | ${escapeCell(check.notes)} |`,
      )
    }
    lines.push('')
  }

  lines.push(...renderDensity(review.density))
  lines.push(...renderConcepts(review.concepts))

  if (Array.isArray(review.checklist) && review.checklist.length) {
    lines.push('## 自审清单', '', '| 检查项 | 结果 | 说明 |', '|---|---|---|')
    for (const item of review.checklist) {
      lines.push(
        `| ${escapeCell(item.item)} | ${escapeCell(item.status)} | ${escapeCell(item.notes)} |`,
      )
    }
    lines.push('')
  }

  if (Array.isArray(review.issues) && review.issues.length) {
    lines.push('## 问题', '', '| 问题 | 严重度 | 已修复 |', '|---|---|---|')
    for (const issue of review.issues) {
      lines.push(
        `| ${escapeCell(issue.description)} | ${escapeCell(issue.severity)} | ${issue.fixed ? 'yes' : 'no'} |`,
      )
    }
    lines.push('')
  }

  if (typeof review.referenceAdaptation === 'string' && review.referenceAdaptation.trim()) {
    lines.push('## 参考适配', '', review.referenceAdaptation.trim(), '')
  }

  if (Array.isArray(options.screenshotPaths) && options.screenshotPaths.length) {
    lines.push('## 本页截图', '')
    for (const screenshot of options.screenshotPaths) {
      lines.push(`- \`${screenshot}\``)
    }
    lines.push('')
  }

  lines.push('> 本文件由 JSON 自动生成；请修改 JSON 后重新运行渲染，不要手改本文件。', '')
  return `${lines.join('\n')}\n`
}

export function writeSelfReview(review, { outJson, outMd, root = process.cwd(), screenshotPaths = [] } = {}) {
  if (!outJson) throw new Error('writeSelfReview requires outJson')
  review.reviewedAt = review.reviewedAt || new Date().toISOString()
  fs.mkdirSync(path.dirname(path.resolve(root, outJson)), { recursive: true })
  fs.writeFileSync(path.resolve(root, outJson), `${JSON.stringify(review, null, 2)}\n`)
  if (outMd) {
    fs.mkdirSync(path.dirname(path.resolve(root, outMd)), { recursive: true })
    fs.writeFileSync(
      path.resolve(root, outMd),
      renderSelfReviewMarkdown(review, { screenshotPaths }),
    )
  }
}

export function parseFlagValue(args, name, fallback = '') {
  const index = args.indexOf(name)
  return index >= 0 && args[index + 1] && !args[index + 1].startsWith('--')
    ? args[index + 1]
    : fallback
}

export function hasFlag(args, name) {
  return args.includes(name)
}
