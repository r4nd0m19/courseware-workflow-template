#!/usr/bin/env node
// Assemble a production site from a shell package plus lesson inputs.
//
// The shell contributes chrome, renderer and static assets. Lesson inputs are
// the deck data, optional narration/voice files, and generated illustration
// variants. reference/ is never copied into the output.
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { readJson, resolveShellDir, validateShellPackage } from './shell-lib.mjs'

const args = process.argv.slice(2)
function opt(name, fallback = '') {
  const i = args.indexOf(name)
  return i >= 0 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : fallback
}
function flag(name) { return args.includes(name) }

let shellDir
try {
  shellDir = resolveShellDir(opt('--shell', 'branch-choice'))
} catch (error) {
  console.error(`FAIL ${error.message}`)
  process.exit(2)
}
const deckPath = opt('--deck')
const outDir = path.resolve(opt('--out', 'prototype/shell-site'))
const artPath = opt('--art')
const narrationPath = opt('--narration')
const audioDir = opt('--audio-dir')
const narrationPlanPath = opt('--narration-plan')
const voiceManifestPath = opt('--voice-manifest')
const requireArt = !flag('--allow-missing-art')
const force = flag('--force')

if (!deckPath) {
  console.error('usage: node prepare-shell-site.mjs --shell shells/<id> --deck <deck.json> --out <site-dir> --art <art.json> [--narration <narration.json>] [--audio-dir <dir>] [--allow-missing-art] [--force]')
  process.exit(2)
}
const check = validateShellPackage(shellDir)
if (!check.ok) {
  console.error(`FAIL shell package\n${check.errors.map((e) => `  - ${e}`).join('\n')}`)
  process.exit(1)
}
const { shell } = check

function sha256(file) {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex')
}
function copyFile(src, dest) {
  fs.mkdirSync(path.dirname(dest), { recursive: true })
  fs.copyFileSync(src, dest)
}
function walk(dir) {
  const out = []
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...walk(full))
    else if (entry.isFile()) out.push(full)
  }
  return out
}
function fail(message) {
  console.error(`FAIL ${message}`)
  process.exit(1)
}

if (fs.existsSync(outDir)) {
  const entries = fs.readdirSync(outDir).filter((n) => n !== '.DS_Store')
  if (entries.length && !force) fail(`output directory is not empty: ${outDir} (pass --force to replace)`)
  if (force) fs.rmSync(outDir, { recursive: true, force: true })
}

// 1. Copy the shell site. reference/ and any narration clips are not part of
//    the shell package and therefore cannot leak into the output.
fs.mkdirSync(outDir, { recursive: true })
for (const file of walk(check.siteDir)) {
  const rel = path.relative(check.siteDir, file)
  copyFile(file, path.join(outDir, rel))
}

// 2. Deck data.
const deck = readJson(path.resolve(deckPath), 'deck')
const deckMeta = deck.meta || deck.COURSEWARE_META || {}
const deckSlides = deck.slides || deck.COURSEWARE_SLIDES || []
if (!deckMeta || typeof deckMeta !== 'object' || Array.isArray(deckMeta)) fail('deck.meta must be an object')
if (!Array.isArray(deckSlides) || deckSlides.length === 0) fail('deck.slides must be a non-empty array')
const allowedTypes = new Set(shell.dataContract.slideTypes)
for (const [i, slide] of deckSlides.entries()) {
  if (!slide || typeof slide !== 'object') fail(`deck.slides[${i}] is not an object`)
  if (!allowedTypes.has(slide.type)) fail(`deck.slides[${i}].type "${slide.type}" is not supported by shell ${shell.id}`)
  for (const key of Object.keys(slide)) {
    if (/^(html|rawHtml|rawHTML|innerHTML|className|style|on[A-Z].*)$/.test(key)) fail(`deck.slides[${i}].${key} is not allowed in declarative deck data`)
  }
}
const deckJs = `// Generated by workflow/tools/prepare-shell-site.mjs from ${path.basename(deckPath)}.
window.COURSEWARE_SHELL_DATA = ${JSON.stringify({ meta: deckMeta, slides: deckSlides }, null, 2)};
`
fs.writeFileSync(path.join(outDir, 'deck.js'), deckJs)

// 3. Illustrations: every declared slot should come from a generated variant.
const generatedArt = {}
if (artPath) {
  const art = readJson(path.resolve(artPath), 'art')
  if (art.shell && art.shell !== shell.id) fail(`art manifest is for shell ${art.shell}, not ${shell.id}`)
  const images = art.images || art.slots || {}
  for (const illustration of shell.assets.illustrations || []) {
    const entry = images[illustration.slot]
    if (!entry) continue
    const src = entry.src || entry.file
    if (!src) fail(`art.${illustration.slot}: src/file is missing`)
    const abs = path.resolve(path.dirname(path.resolve(artPath)), src)
    if (!fs.existsSync(abs)) fail(`art.${illustration.slot}: file not found ${abs}`)
    const expected = entry.sha256 || entry.generatedSha256
    if (expected && sha256(abs) !== expected) fail(`art.${illustration.slot}: hash mismatch`)
    if (illustration.referenceSha256 && sha256(abs) === illustration.referenceSha256) {
      fail(`art.${illustration.slot}: generated file is byte-identical to the reference; generate a distinct variant`)
    }
    const ext = path.extname(abs) || '.png'
    const destRel = `assets/generated/${illustration.slot}${ext}`
    copyFile(abs, path.join(outDir, destRel))
    generatedArt[illustration.slot] = {
      src: destRel,
      alt: illustration.alt || entry.alt || '',
      className: illustration.className || 'pixel-student generated-mascot',
      blend: illustration.blend || 'multiply',
      prompt: entry.prompt || illustration.prompt || '',
      seed: entry.seed ?? null,
      model: entry.model || art.model || '',
      provider: entry.provider || art.provider || '',
      generatedSha256: sha256(abs),
      trimmed: entry.trimmed ?? null,
      pixelated: entry.pixelated ?? null,
      pixelHeight: entry.pixelHeight ?? null,
      pixelScale: entry.pixelScale ?? null,
    }
  }
}
const missingArt = (shell.assets.illustrations || []).filter((art) => !generatedArt[art.slot]).map((art) => art.slot)
if (requireArt && missingArt.length) fail(`missing generated illustration variant(s): ${missingArt.join(', ')}; run generate-shell-art.mjs (use --allow-missing-art only for a shell preview, never for a lesson build)`)
const artData = missingArt.length
  ? `// No generated art for: ${missingArt.join(', ')}. The shell falls back to its inline reference art.\nwindow.COURSEWARE_SHELL_ART = {};\n`
  : `// Generated per-lesson illustration variants. Reference crops are not copied.\nwindow.COURSEWARE_SHELL_ART = ${JSON.stringify(generatedArt, null, 2)};\n`
fs.writeFileSync(path.join(outDir, 'shell-art-data.js'), artData)

// 4. Narration. Two supported inputs:
//    - shell-format JS files (COURSEWARE_* globals)
//    - the repo's narration.json manifest, converted here.
const narrationFiles = []
if (narrationPlanPath) {
  const source = fs.readFileSync(path.resolve(narrationPlanPath), 'utf8')
  if (!source.includes('COURSEWARE_NARRATION_PLAN')) fail('--narration-plan must define window.COURSEWARE_NARRATION_PLAN')
  fs.writeFileSync(path.join(outDir, 'narration-plan.js'), source)
  narrationFiles.push('narration-plan.js')
}
if (voiceManifestPath) {
  const source = fs.readFileSync(path.resolve(voiceManifestPath), 'utf8')
  if (!source.includes('COURSEWARE_VOICE_MANIFEST')) fail('--voice-manifest must define window.COURSEWARE_VOICE_MANIFEST')
  fs.writeFileSync(path.join(outDir, 'voice-manifest.js'), source)
  narrationFiles.push('voice-manifest.js')
}
if (narrationPath) {
  if (narrationPlanPath || voiceManifestPath) fail('use either --narration or --narration-plan/--voice-manifest, not both')
  const manifest = readJson(path.resolve(narrationPath), 'narration')
  const voices = (manifest.voices || []).map((voice) => ({ id: voice.id, name: voice.displayName || voice.name, voice: voice.providerVoice || voice.voice }))
  const voiceIds = voices.map((voice) => voice.id)
  if (!voices.length) fail('narration.voices is empty')
  const clipIndex = new Map((manifest.clips || []).map((clip) => [`${clip.id}/${clip.voice}`, clip]))
  const narrationSlides = manifest.slides || []
  if (!narrationSlides.length) fail('narration.slides is empty')
  let aligned = narrationSlides
  if (narrationSlides.every((slide) => slide.id)) {
    const byId = new Map(narrationSlides.map((slide) => [slide.id, slide]))
    const missing = deckSlides.filter((slide) => !byId.has(slide.id)).map((slide) => slide.id)
    if (missing.length) fail(`narration is missing deck slide(s): ${missing.join(', ')}`)
    // A wider manifest may cover later sections; keep only this deck's slides
    // and order the pages exactly like the deck.
    aligned = deckSlides.map((slide) => byId.get(slide.id))
  } else {
    aligned = narrationSlides.slice(0, deckSlides.length)
    if (aligned.length < deckSlides.length) {
      fail(`narration covers ${aligned.length} slide(s) but the deck has ${deckSlides.length}`)
    }
  }
  const pages = []
  for (const [i, slide] of aligned.entries()) {
    if (!slide.spokenText) fail(`narration.slides[${i}] (${slide.id}) has no spokenText`)
    const files = {}
    for (const voice of voiceIds) {
      const raw = slide.audio?.[voice]
      if (!raw) fail(`narration.slides[${i}] (${slide.id}) has no audio for ${voice}`)
      let rel
      if (/^https?:\/\//i.test(raw)) {
        if (audioDir) fail(`remote narration audio cannot be copied with --audio-dir: ${raw}`)
        rel = raw
      } else if (audioDir) {
        // Manifests may store site-absolute URLs such as /audio/S01/xiaozhi.mp3.
        // Resolve them below --audio-dir, not at the filesystem root.
        const relative = raw.replace(/^\/+/, '').replace(/^audio\//, '')
        if (path.isAbsolute(relative) || relative.split(/[\\/]/).includes('..')) {
          fail(`narration audio path is not safe: ${raw}`)
        }
        const audioRoot = path.resolve(audioDir)
        const sourceFile = path.resolve(audioRoot, relative)
        if (!sourceFile.startsWith(`${audioRoot}${path.sep}`)) {
          fail(`narration audio path escapes --audio-dir: ${raw}`)
        }
        if (!fs.existsSync(sourceFile)) fail(`narration audio missing: ${sourceFile}`)
        // Keep slide and voice in the destination path: every slide has a clip
        // with the same basename (e.g. xiaozhi.mp3).
        rel = `assets/narration/${slide.id}/${voice}${path.extname(sourceFile) || '.mp3'}`
        copyFile(sourceFile, path.join(outDir, rel))
      } else {
        rel = raw
        if (!fs.existsSync(path.join(outDir, rel.replace(/^\/+/, '')))) {
          fail(`narration audio ${rel} is not in the site and --audio-dir was not provided`)
        }
      }
      const meta = clipIndex.get(`${slide.id}/${voice}`)
      files[voice] = { src: rel, duration: Number(meta?.durationSeconds) || 0 }
    }
    pages.push({
      title: slide.title || slide.id,
      segments: [{ kind: 'audio', id: 'main', text: slide.spokenText, files }],
    })
  }
  const voiceManifest = `// Generated by prepare-shell-site.mjs from ${path.basename(narrationPath)}.
window.COURSEWARE_VOICE_MANIFEST = ${JSON.stringify({ version: 1, voices, pages }, null, 2)};
`
  fs.writeFileSync(path.join(outDir, 'voice-manifest.js'), voiceManifest)
  const narrationPlan = `// Generated by prepare-shell-site.mjs from ${path.basename(narrationPath)}.
window.COURSEWARE_NARRATION_PLAN = ${JSON.stringify({
    version: 1,
    pages: pages.map((page) => ({ title: page.title, segments: page.segments.map((segment) => ({ kind: segment.kind, id: segment.id, text: segment.text })) })),
  }, null, 2)};
`
  fs.writeFileSync(path.join(outDir, 'narration-plan.js'), narrationPlan)
  narrationFiles.push('narration-plan.js', 'voice-manifest.js')
}

// 5. Build provenance for the workflow to review.
const buildManifest = {
  schemaVersion: '1.0',
  shell: { id: shell.id, name: shell.name, version: shell.version, profile: shell.profile },
  deck: {
    file: path.basename(deckPath),
    sha256: sha256(path.resolve(deckPath)),
    slides: deckSlides.length,
    types: deckSlides.map((slide) => slide.type),
    title: deckMeta.title || '',
  },
  illustrations: generatedArt,
  missingArt,
  narration: narrationFiles,
  policy: shell.policy,
  generatedAt: new Date().toISOString(),
}
fs.writeFileSync(path.join(outDir, 'build-manifest.json'), `${JSON.stringify(buildManifest, null, 2)}\n`)

console.log(`OK site ${path.relative(process.cwd(), outDir) || outDir}`)
console.log(`   shell: ${shell.id}@${shell.version}`)
console.log(`   slides: ${deckSlides.length} (${[...new Set(deckSlides.map((s) => s.type))].join(', ')})`)
console.log(`   generated art: ${Object.keys(generatedArt).join(', ') || 'none'}`)
if (missingArt.length) console.log(`   WARN missing art (allowed by --allow-missing-art): ${missingArt.join(', ')}`)
else if (!artPath) console.log('   art: none')
console.log(`   narration: ${narrationFiles.join(', ') || 'none (shell stubs)'}`)
