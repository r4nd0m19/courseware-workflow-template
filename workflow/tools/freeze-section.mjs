#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import { readData } from './lib.mjs'
import {
  assertScriptApproved,
  DEFAULT_PAGE_APPROVALS,
  DEFAULT_SCREENSHOTS_DIR,
  DEFAULT_SCRIPT_APPROVAL,
} from './approval-lib.mjs'
import { requirePageGateApproval } from './review-guard.mjs'
import { parseScript } from './script-lib.mjs'
import {
  approvalProblems,
  fileHash,
  readApprovals,
  readSectionManifest,
  sectionById,
  slideScriptHash,
  validateSectionManifest,
  writeApprovals,
} from './section-lib.mjs'

const args = process.argv.slice(2)
function opt(name, fallback = '') {
  const i = args.indexOf(name)
  return i >= 0 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : fallback
}
function flag(name) {
  return args.includes(name)
}

const sectionsPath = opt('--sections')
const storyboardPath = opt('--storyboard')
const scriptPath = opt('--script')
const screenshots = opt('--screenshots', DEFAULT_SCREENSHOTS_DIR)
const approvalsPath = opt('--approvals', DEFAULT_PAGE_APPROVALS)
const approvalPath = opt('--approval', DEFAULT_SCRIPT_APPROVAL)
const sectionId = opt('--id')
const approvedBy = opt('--approved-by')

if (
  !sectionsPath ||
  !storyboardPath ||
  !scriptPath ||
  !sectionId ||
  !approvedBy
) {
  console.error(`usage: node freeze-section.mjs --sections <file> --storyboard <file> --script <courseware.md> --id <section> --approved-by <name> [options]

Options:
  --screenshots <dir>   rendered screenshots (default: screenshots)
  --approvals <path>    approval ledger (default: review/page-approvals.json)
  --approval <path>     whole-script approval ledger (default: review/script-approval.json)
  --manual              allow a manual/test freeze without a review-page gate
`)
  process.exit(2)
}

requirePageGateApproval({
  tool: `freeze-section ${sectionId}`,
  sectionId,
  manual: flag('--manual'),
})

try {
  assertScriptApproved(scriptPath, { approvalPath })
} catch (error) {
  console.error(`FAIL script approval\n${(error.problems || [error.message]).map((p) => `  ${p}`).join('\n')}`)
  process.exit(1)
}

const manifest = readSectionManifest(sectionsPath)
const storyboard = readData(storyboardPath)
const parsed = parseScript(scriptPath)
const slides = storyboard.slides || []
const errors = validateSectionManifest(manifest, slides, { requireAll: true })
if (errors.length) {
  console.error(`FAIL review sections\n${errors.map((e) => `  ${e}`).join('\n')}`)
  process.exit(1)
}

const section = sectionById(manifest, sectionId)
if (!section) {
  console.error(`FAIL section ${sectionId} is not declared in ${sectionsPath}`)
  process.exit(1)
}

const byId = new Map(slides.map((s) => [s.id, s]))
for (const id of section.slides) {
  const slide = byId.get(id)
  if (!slide || slide.status !== 'APPROVED') {
    console.error(`FAIL section ${sectionId}: slide ${id} is not APPROVED`)
    process.exit(1)
  }
}

const scriptById = new Map(parsed.slides.map((s) => [s.id, s]))
const approvals = readApprovals(approvalsPath)
const prior = {
  ...approvals,
  sections: { ...(approvals.sections || {}) },
}
delete prior.sections[sectionId]
const problems = approvalProblems(prior, manifest, parsed.slides, { screenshots })
if (problems.length) {
  console.error(`FAIL approved sections changed\n${problems.map((p) => `  ${p}`).join('\n')}`)
  process.exit(1)
}

const frozenSlides = {}
for (const id of section.slides) {
  const scriptSlide = scriptById.get(id)
  if (!scriptSlide) {
    console.error(`FAIL section ${sectionId}: slide ${id} is missing from the script`)
    process.exit(1)
  }
  const screenshot = path.join(screenshots, `${id}.png`)
  if (!fs.existsSync(screenshot)) {
    console.error(`FAIL section ${sectionId}: screenshot missing for ${id} (${screenshot})`)
    process.exit(1)
  }
  frozenSlides[id] = {
    scriptHash: slideScriptHash(scriptSlide),
    screenshot,
    screenshotHash: fileHash(screenshot),
  }
}

const approvedAt = new Date().toISOString()
approvals.script = path.relative(process.cwd(), path.resolve(scriptPath))
approvals.sections[sectionId] = {
  title: section.title,
  approvedBy,
  approvedAt,
  slides: frozenSlides,
}
writeApprovals(approvalsPath, approvals)

const ledger = [
  '# Rendered section approvals',
  '',
  'Generated by `freeze-section.mjs` after a human section review gate. Do not edit by hand.',
  '',
  '| Section | Title | Slides | Approved by | Approved at |',
  '|---|---|---|---|---|',
  ...manifest.sections
    .filter((s) => approvals.sections[s.id])
    .map((s) => {
      const a = approvals.sections[s.id]
      return `| ${s.id} | ${s.title} | ${s.slides.join(', ')} | ${a.approvedBy} | ${a.approvedAt} |`
    }),
  '',
]
const ledgerPath = path.join(path.dirname(approvalsPath), 'page-approvals.md')
fs.mkdirSync(path.dirname(ledgerPath), { recursive: true })
fs.writeFileSync(ledgerPath, ledger.join('\n'))

console.log(
  `OK section ${sectionId} approved — ${section.slides.length} slide(s) frozen; ${Object.keys(approvals.sections).length}/${manifest.sections.length} section(s) reviewed`,
)
