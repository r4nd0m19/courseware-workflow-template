#!/usr/bin/env node
// Build the deck's component bundle from the approved registry. The deck never
// imports staged/private code, and a component without a browser runtime fails
// here instead of being hand-copied into a page.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const args = process.argv.slice(2)
function opt(name, fallback = '') {
  const i = args.indexOf(name)
  return i >= 0 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : fallback
}
function flag(name) { return args.includes(name) }
const registryPath = path.resolve(opt('--registry', 'registry/index.json'))
const outFile = path.resolve(opt('--out', 'prototype/site/components.bundle.js'))
const cssOut = path.resolve(opt('--css-out', 'prototype/site/components.bundle.css'))
const siteDir = path.resolve(opt('--site', 'prototype/site'))
const check = flag('--check')
const jsonOut = flag('--json')

const errors = []
const notes = []
if (!fs.existsSync(registryPath)) {
  console.error(`FAIL registry not found: ${registryPath}`)
  process.exit(2)
}
const registry = JSON.parse(fs.readFileSync(registryPath, 'utf8'))
const registryRoot = path.dirname(registryPath)
const stagingArg = opt('--staging')
const stagingDir = stagingArg ? path.resolve(stagingArg) : ''
const modules = []
const styles = []
const bundled = new Set()

function bundlePackage({ id, version, packageDir, source, provenance }) {
  const manifestFile = path.join(packageDir, 'component.json')
  if (!fs.existsSync(manifestFile)) { errors.push(`${id}: missing component.json at ${manifestFile}`); return }
  const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'))
  if (manifest.id !== id) errors.push(`${id}: component.json id is ${manifest.id}`)
  if (manifest.status !== 'core') errors.push(`${id}: package status ${manifest.status} is not core`)
  const impl = String(manifest.implementation || '')
  if (!impl) { errors.push(`${id}: implementation is missing`); return }
  if (!impl.endsWith('.js')) {
    errors.push(`${id}: implementation "${impl}" is not a browser .js runtime; the data-driven deck cannot import JSX/MDX`)
    return
  }
  const implFile = path.join(packageDir, impl)
  if (!fs.existsSync(implFile)) { errors.push(`${id}: implementation file missing: ${implFile}`); return }
  const code = fs.readFileSync(implFile, 'utf8')
  const registerPattern = new RegExp(`CoursewareComponents\\.register\\(\\s*['"]${id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}['"]`)
  if (!registerPattern.test(code)) errors.push(`${id}: runtime must call CoursewareComponents.register('${id}', …)`)
  modules.push(`// ${source}: ${id}@${version} (${manifest.provenance?.type || provenance})` + '\n' + code)
  for (const style of manifest.styles || []) {
    const styleFile = path.join(packageDir, style)
    if (!fs.existsSync(styleFile)) { errors.push(`${id}: styles file missing: ${styleFile}`); continue }
    styles.push(`/* ${source}: ${id}@${version} — ${style} */\n${fs.readFileSync(styleFile, 'utf8')}`)
  }
  bundled.add(id)
  notes.push(`${source === 'staged' ? 'staged ' : ''}${id}@${version}`)
}

for (const entry of registry.components || []) {
  if (entry.status !== 'core') { notes.push(`skip ${entry.id}: status=${entry.status}`); continue }
  bundlePackage({
    id: entry.id,
    version: entry.version,
    packageDir: path.resolve(registryRoot, entry.package),
    source: 'registry',
    provenance: 'unknown',
  })
}

// Staged packages are built for the current page and bundled so the page can
// be rendered and reviewed before the component enters core. They are removed
// from staging by register-staged-components --clean after the page is approved.
if (stagingDir && fs.existsSync(stagingDir)) {
  const staged = fs
    .readdirSync(stagingDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => path.join(stagingDir, d.name))
    .filter((dir) => fs.existsSync(path.join(dir, 'component.json')))
  for (const dir of staged) {
    let manifest
    try {
      manifest = JSON.parse(fs.readFileSync(path.join(dir, 'component.json'), 'utf8'))
    } catch (err) {
      errors.push(`${path.basename(dir)}: invalid component.json (${err.message})`)
      continue
    }
    if (bundled.has(manifest.id)) continue
    bundlePackage({
      id: manifest.id,
      version: manifest.version,
      packageDir: dir,
      source: 'staged',
      provenance: manifest.provenance?.type || 'unknown',
    })
  }
}

const bundle = `// Generated by workflow/tools/sync-deck-components.mjs. Do not edit.
// Source: ${path.relative(process.cwd(), registryPath)}
(function () {
  // Merge with any harness registrations already present; a generated bundle
  // must not silently discard components registered earlier in the page.
  const registry = (window.CoursewareComponents && window.CoursewareComponents._registry) || new Map();
  window.CoursewareComponents = {
    _registry: registry,
    register(id, implementation) { registry.set(id, implementation); },
    get(id) { return registry.get(id); },
    has(id) { return registry.has(id); },
    types() { return [...registry.keys()]; }
  };
})();
${modules.join('\n;\n\n')}
`
const cssBundle = `/* Generated by workflow/tools/sync-deck-components.mjs. Do not edit. */\n${styles.join('\n\n')}\n`

function writeOrCheck(file, content) {
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) errors.push(`stale generated file: ${file} (run sync-deck-components without --check)`)
    return
  }
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, content)
}
writeOrCheck(outFile, bundle)
if (styles.length) writeOrCheck(cssOut, cssBundle)

const indexFile = path.join(siteDir, 'index.html')
if (fs.existsSync(indexFile) && modules.length) {
  let html = fs.readFileSync(indexFile, 'utf8')
  let changed = false
  // The shell lesson renderer has no component host of its own. Its deck uses
  // `blank` slides with a `component` field, so the bundle loads before
  // lesson.js and the host adapter loads after it.
  const shellSite = /<script src="(?:\.\/)?lesson\.js"><\/script>/.test(html)
  if (styles.length && !html.includes('./components.bundle.css')) {
    if (check) errors.push(`site index.html does not load ./components.bundle.css: ${indexFile}`)
    else {
      html = html.replace('</head>', '  <link rel="stylesheet" href="./components.bundle.css">\n</head>')
      changed = true
    }
  }
  if (shellSite) {
    const hostSource = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'runtime', 'shell-component-host.js')
    const hostTarget = path.join(siteDir, 'shell-components.js')
    if (!fs.existsSync(hostSource)) {
      errors.push(`shell component host source missing: ${hostSource}`)
    } else if (check) {
      if (!fs.existsSync(hostTarget) || fs.readFileSync(hostTarget, 'utf8') !== fs.readFileSync(hostSource, 'utf8')) {
        errors.push(`stale generated file: ${hostTarget} (run sync-deck-components without --check)`)
      }
    } else {
      fs.copyFileSync(hostSource, hostTarget)
    }
    if (check) {
      const bundleAt = html.indexOf('./components.bundle.js')
      const hostAt = html.indexOf('./shell-components.js')
      const lessonMatch = /<script src="(?:\.\/)?lesson\.js"><\/script>/.exec(html)
      const lessonAt = lessonMatch ? lessonMatch.index : -1
      if (bundleAt < 0) errors.push(`site index.html does not load ./components.bundle.js: ${indexFile}`)
      if (hostAt < 0) errors.push(`site index.html does not load ./shell-components.js: ${indexFile}`)
      if (bundleAt >= 0 && lessonAt >= 0 && bundleAt > lessonAt) errors.push(`site index.html must load ./components.bundle.js before lesson.js: ${indexFile}`)
      if (hostAt >= 0 && lessonAt >= 0 && hostAt < lessonAt) errors.push(`site index.html must load ./shell-components.js after lesson.js: ${indexFile}`)
    } else {
      if (!html.includes('./components.bundle.js')) {
        html = html.replace(/(\s*)(<script src="(?:\.\/)?lesson\.js"><\/script>)/, '$1<script src="./components.bundle.js"></script>$1$2')
        changed = true
      }
      if (!html.includes('./shell-components.js')) {
        html = html.replace(/(<script src="(?:\.\/)?lesson\.js"><\/script>)/, '$1\n  <script src="./shell-components.js"></script>')
        changed = true
      }
    }
  } else if (!html.includes('./components.bundle.js')) {
    if (check) errors.push(`site index.html does not load ./components.bundle.js: ${indexFile}`)
    else {
      html = html.replace(/(<script src="\.\/slides[^"]*\.js"><\/script>)/, '<script src="./components.bundle.js"></script>\n  $1')
      if (!html.includes('./components.bundle.js')) html = html.replace('</body>', '<script src="./components.bundle.js"></script>\n</body>')
      changed = true
    }
  }
  if (!check && changed) fs.writeFileSync(indexFile, html)
}

const report = { ok: errors.length === 0, components: notes, errors, out: path.relative(process.cwd(), outFile) }
if (jsonOut) console.log(JSON.stringify(report, null, 2))
else {
  for (const note of notes) console.log(`note: bundled ${note}`)
  for (const error of errors) console.log(`ERROR: ${error}`)
  console.log(`${report.ok ? 'OK' : 'FAIL'} deck component bundle${check ? ' (check)' : ''}`)
}
process.exit(report.ok ? 0 : 1)
