#!/usr/bin/env node
// Write the deck's audio adapter (window.LESSON_*) from the generated narration
// manifest. Keeps the copied reference audio engine data-driven.
import fs from 'node:fs'
import path from 'node:path'

const args = process.argv.slice(2)
function opt(name, fallback = '') {
  const i = args.indexOf(name)
  return i >= 0 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : fallback
}
function flag(name) { return args.includes(name) }
const manifestPath = args.find((a) => !a.startsWith('--'))
const outFile = path.resolve(opt('--out', 'prototype/site/audio.js'))
const check = flag('--check')
const jsonOut = flag('--json')
if (!manifestPath) {
  console.error('usage: node build-audio-adapter.mjs <narration.json> --out prototype/site/audio.js [--check] [--json]')
  process.exit(2)
}
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
const errors = []
const warnings = []
const voices = (manifest.voices || []).map((v) => ({ id: v.id, name: v.displayName, voice: v.providerVoice }))
const voiceIds = voices.map((v) => v.id)
const clips = {}
const durations = {}
const narration = {}
const pages = []
const clipIndex = new Map((manifest.clips || []).map((c) => [`${c.id}/${c.voice}`, c]))
for (const slide of manifest.slides || []) {
  if (!slide.spokenText) { errors.push(`${slide.id}: missing spokenText`); continue }
  const text = slide.spokenText
  if (narration[slide.id] && narration[slide.id] !== text) errors.push(`${slide.id}: duplicate narration id with different text`)
  if (narration[slide.title] && narration[slide.title] !== text) errors.push(`${slide.title}: duplicate narration title with different text`)
  narration[slide.id] = text
  narration[slide.title] = text
  clips[text] ||= {}
  let pageDuration = 0
  for (const voice of voiceIds) {
    const src = slide.audio?.[voice]
    if (!src) { errors.push(`${slide.id}: missing audio for voice ${voice}`); continue }
    clips[text][voice] = src
    const meta = clipIndex.get(`${slide.id}/${voice}`)
    const seconds = Number(meta?.durationSeconds) || 0
    durations[src] = seconds
    pageDuration += seconds
  }
  pages.push({ id: slide.id, title: slide.title, duration: Math.max(1, Math.round(pageDuration)), segments: [] })
}
const content = `// Generated by workflow/tools/build-audio-adapter.mjs from ${path.relative(process.cwd(), manifestPath)}. Do not edit.
// Provider: ${manifest.provider || 'unknown'} (${manifest.generator || 'unknown'}); source hash: ${manifest.sourceHash || 'unknown'}
window.LESSON_AUTOPLAY_CONFIG = ${JSON.stringify({
  audioVersion: `narration-${String(manifest.sourceHash || '').slice(0, 12)}`,
  transitionSeconds: 2,
  voices,
  pages,
}, null, 2)};
window.LESSON_NARRATION = ${JSON.stringify(narration, null, 2)};
window.LESSON_EXPLANATIONS = ${JSON.stringify(manifest.explanations || {}, null, 2)};
window.LESSON_VOICE_MANIFEST = ${JSON.stringify({ voices, clips }, null, 2)};
window.LESSON_VOICE_DURATIONS = ${JSON.stringify(durations, null, 2)};
`
if (!check) {
  fs.mkdirSync(path.dirname(outFile), { recursive: true })
  fs.writeFileSync(outFile, content)
} else if (!fs.existsSync(outFile) || fs.readFileSync(outFile, 'utf8') !== content) {
  errors.push(`stale generated file: ${outFile} (run build-audio-adapter without --check)`)
}
const report = { ok: errors.length === 0, slides: pages.length, voices: voices.length, errors, warnings, out: path.relative(process.cwd(), outFile) }
if (jsonOut) console.log(JSON.stringify(report, null, 2))
else {
  for (const w of warnings) console.log(`warn: ${w}`)
  for (const e of errors) console.log(`ERROR: ${e}`)
  console.log(`${report.ok ? 'OK' : 'FAIL'} audio adapter — ${pages.length} slide(s), ${voices.length} voice(s)${check ? ' (check)' : ''}`)
}
process.exit(report.ok ? 0 : 1)
